create or replace function pg_temp.portal_seed_official_name(p_name text) returns text
language sql immutable set search_path='' as $$
 select case when n='juliuserwinalpas' then 'juliuserwintalpas' else n end from (
  select regexp_replace(translate(regexp_replace(regexp_replace(lower(trim(p_name)),
   '^hon([.][[:space:]]*|[[:space:]]+)','',''),'^atty([.][[:space:]]*|[[:space:]]+)','',''),
   'ñ','n'),'[[:space:].]+','','g') n
 ) normalized;
$$;
create or replace function pg_temp.portal_seed_committee_name(p_name text) returns text
language sql immutable set search_path='' as $$
 select regexp_replace(lower(replace(p_name,'&','and')),'[^[:alnum:]]','','g');
$$;
create or replace function pg_temp.portal_seed_document_number(p_number text) returns text
language sql immutable set search_path='' as $$
 select lower(regexp_replace(trim(regexp_replace(p_number,
  '^[[:space:]]*(ordinance|resolution)[[:space:]]+no[.][[:space:]]*','','i')),'[[:space:]]+',' ','g'));
$$;

-- Resolve every reference before writing permanent content. Never guess an
-- ambiguous identity, create a missing session, or adopt an unassigned document.
do $$
declare resolved_office uuid; resolved_term uuid; matches integer; seed record;
 guard record; table_name text; author_ref text; coauthor_ref text; committee_ref text;
 session_ref text; found_id text; current_row jsonb;
begin
 select count(*),min(id::text)::uuid into matches,resolved_office from public.departments
  where department='legislative' and active and archived_at is null;
 if matches<>1 then raise exception 'Expected one active Legislative Access office'; end if;
 select count(*),min(id::text)::uuid into matches,resolved_term from public.legislative_terms
  where start_date=date '2025-07-01' and end_date=date '2028-06-30';
 if matches<>1 then raise exception 'Expected one existing 2025-2028 Legislative Term'; end if;
 insert into portal_document_seed_context values(resolved_office,resolved_term);
 foreach table_name in array array['ordinances','resolutions'] loop
  if not exists(select 1 from pg_attribute where attrelid=format('public.%I',table_name)::regclass
   and attname='approval_mode' and not attisdropped) then
   raise exception 'Apply migration 037 before importing Legislative documents';
  end if;
  for guard in select * from (values
   ('z_reorder','portal_reorder_content'),('a_document_session_authors','portal_document_session_authors'),
   ('assign_legislative_term','portal_term_assignment'),('legislative_relations','portal_legislative_relations')
  ) expected(trigger_name,function_name) loop
   if not exists(select 1 from pg_trigger t join pg_proc p on p.oid=t.tgfoid
    where t.tgrelid=format('public.%I',table_name)::regclass and t.tgname=guard.trigger_name
     and t.tgenabled='O' and p.proname=guard.function_name) then
    raise exception 'Unexpected % trigger state on %; review before importing',guard.trigger_name,table_name;
   end if;
  end loop;
 end loop;
 if (select count(*) from portal_legislative_document_seed)<>210
  or (select count(*) from portal_legislative_document_seed where collection='ordinances')<>69
  or (select count(*) from portal_legislative_document_seed where collection='resolutions')<>141
  or exists(select 1 from portal_legislative_document_seed s
   where s.date_approved not between date '2025-07-01' and date '2028-06-30'
    or trim(s.title)='' or s.source_rows && array[501,537])
  or exists(select 1 from portal_legislative_document_seed group by collection,
   pg_temp.portal_seed_document_number(number),extract(year from date_approved) having count(*)<>1) then
  raise exception 'Unexpected approved document roster; no changes committed';
 end if;
 for seed in select * from portal_legislative_document_seed order by source_row loop
  select count(*),min(id) into matches,author_ref from public.officials
   where office_id=resolved_office and content_scope='legislative' and term_id=resolved_term
    and legislative_role='SANGGUNIANG_BAYAN'
    and pg_temp.portal_seed_official_name(name)=pg_temp.portal_seed_official_name(seed.author_name);
  if matches<>1 then raise exception 'Excel row %: missing or ambiguous SB author %',seed.source_row,seed.author_name; end if;
  coauthor_ref=null;
  if seed.co_author_name is not null then
   select count(*),min(id) into matches,coauthor_ref from public.officials
    where office_id=resolved_office and content_scope='legislative' and term_id=resolved_term
     and legislative_role='SANGGUNIANG_BAYAN'
     and pg_temp.portal_seed_official_name(name)=pg_temp.portal_seed_official_name(seed.co_author_name);
   if matches<>1 then raise exception 'Excel row %: missing or ambiguous SB co-author %',seed.source_row,seed.co_author_name; end if;
  end if;
  if author_ref=coauthor_ref then raise exception 'Excel row %: author and co-author must differ',seed.source_row; end if;
  select count(*),min(id) into matches,committee_ref from public.committees
   where office_id=resolved_office and content_scope='legislative' and term_id=resolved_term
    and pg_temp.portal_seed_committee_name(name)=pg_temp.portal_seed_committee_name(seed.committee_name);
  if matches<>1 then raise exception 'Excel row %: missing or ambiguous term-specific committee %',seed.source_row,seed.committee_name; end if;
  select count(*),min(id) into matches,session_ref from public.sessions
   where office_id=resolved_office and content_scope='legislative' and term_id=resolved_term
    and date=seed.date_approved;
  if matches<>1 then raise exception 'Excel row %: expected one existing session on %',seed.source_row,seed.date_approved; end if;
  execute format('select count(*),min(id) from public.%I where office_id=$1 and content_scope=''legislative''
   and year=extract(year from $2::date) and pg_temp.portal_seed_document_number(number)=pg_temp.portal_seed_document_number($3)',seed.collection)
   into matches,found_id using resolved_office,seed.date_approved,seed.number;
  if matches>1 then raise exception 'Excel row %: ambiguous existing document number %',seed.source_row,seed.number; end if;
  if matches=1 then
   execute format('select to_jsonb(d) from public.%I d where id=$1',seed.collection) into current_row using found_id;
   if current_row->>'number' is distinct from seed.number or current_row->>'title' is distinct from seed.title
    or (current_row->>'date_approved')::date is distinct from seed.date_approved
    or (current_row->>'term_id')::uuid is distinct from resolved_term
    or current_row->>'author_id' is distinct from author_ref or current_row->>'co_author_id' is distinct from coauthor_ref
    or current_row->>'committee_id' is distinct from committee_ref or current_row->>'session_id' is distinct from session_ref
    or current_row->>'summary' is distinct from seed.title or current_row->>'pdf_url' is not null
    or current_row->>'author' is distinct from '' or current_row->>'co_author' is not null
    or current_row->>'approval_mode' is distinct from 'authored' or current_row->>'status' is distinct from 'Approved'
    or (current_row->>'published')::boolean is distinct from true or (current_row->>'is_sample')::boolean is distinct from false then
    raise exception 'Excel row %: existing % number % differs; preserve and review it instead of overwriting',seed.source_row,seed.collection,seed.number;
   end if;
  end if;
  update portal_legislative_document_seed set author_id=author_ref,co_author_id=coauthor_ref,
   committee_id=committee_ref,session_id=session_ref,document_id=coalesce(found_id,gen_random_uuid()::text),existing=(matches=1)
   where source_row=seed.source_row;
 end loop;
end;
$$;

