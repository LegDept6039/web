 select 'ordinances'::text collection,id,to_jsonb(o) original from public.ordinances o
 union all select 'resolutions',id,to_jsonb(r) from public.resolutions r;
create temporary table portal_document_references_before on commit drop as
 select 'departments'::text collection,id::text,to_jsonb(d) original from public.departments d
 union all select 'legislative_terms',id::text,to_jsonb(t) from public.legislative_terms t
 union all select 'officials',id,to_jsonb(o) from public.officials o
 union all select 'committees',id,to_jsonb(c) from public.committees c
